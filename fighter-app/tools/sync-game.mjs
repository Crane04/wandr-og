// Brings the web game (../fight) into the app, so both play exactly the same game.
//   npm run sync
// 1. Copies the game logic (fighters, combat, CPU, roster, stage, effects) into
//    src/game/. Those copies are generated: change them in fight/public/js.
// 2. Splits each fighter model into a texture-free .glb plus its texture images,
//    because React Native can't decode images packed inside a .glb.
import fs from 'fs';
import path from 'path';

const app = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const web = path.resolve(app, '../fight/public');
const out = path.join(app, 'src/game');
fs.mkdirSync(out, { recursive: true });

// ---------------------------------------------------------------- logic
const LOGIC = ['fighter.js', 'combat.js', 'ai.js', 'roster.js', 'model.js', 'stage.js', 'fx.js', 'blood.js', 'skin.js'];
const banner = '// GENERATED by tools/sync-game.mjs from fight/public/js. Edit it there, then npm run sync.\n';
for (const f of LOGIC) {
  let src = fs.readFileSync(path.join(web, 'js', f), 'utf8');
  if (src.includes("document.createElement('canvas')")) {
    // browser canvases become the app's software canvas, which draws into a DataTexture
    src = src.replaceAll("document.createElement('canvas')", 'createCanvas()').replaceAll('new THREE.CanvasTexture(', 'canvasTexture(');
    src = src.replace(/^(import \* as THREE from 'three';\n)/m, "$1import { createCanvas, canvasTexture } from '../softcanvas';\n");
  }
  if (f === 'skin.js') {
    // fighters' bodies come from the app's bundled files instead of the web server
    src = src.replace("import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';\n", "import { loadModel } from '../loadModel';\n");
    src = src.replace('new GLTFLoader().loadAsync(`/models/${name}.glb`)', 'loadModel(name)');
    if (src.includes('GLTFLoader')) throw new Error('skin.js: model loading changed, update tools/sync-game.mjs');
  }
  if (/\bdocument\.|\bwindow\.|localStorage/.test(src)) throw new Error(`${f} uses a browser-only API`);
  fs.writeFileSync(path.join(out, f), banner + src);
}
console.log(`logic: ${LOGIC.length} files -> src/game/`);

// ---------------------------------------------------------------- models
const GLB = 0x46546c67, JSON_CHUNK = 0x4e4f534a, BIN_CHUNK = 0x004e4942;
const SLOTS = { baseColorTexture: 'map', normalTexture: 'normalMap', emissiveTexture: 'emissiveMap' };

function readGlb(buf) {
  if (buf.readUInt32LE(0) !== GLB) throw new Error('not a glb');
  let at = 12, json, bin;
  while (at < buf.length) {
    const len = buf.readUInt32LE(at), type = buf.readUInt32LE(at + 4);
    const data = buf.subarray(at + 8, at + 8 + len);
    if (type === JSON_CHUNK) json = JSON.parse(data.toString('utf8'));
    if (type === BIN_CHUNK) bin = data;
    at += 8 + len;
  }
  return { json, bin };
}

function writeGlb(json, bin) {
  const pad = (b, c) => Buffer.concat([b, Buffer.alloc((4 - (b.length % 4)) % 4, c)]);
  const j = pad(Buffer.from(JSON.stringify(json)), 0x20), b = pad(bin, 0);
  const head = Buffer.alloc(12);
  head.writeUInt32LE(GLB, 0); head.writeUInt32LE(2, 4); head.writeUInt32LE(12 + 8 + j.length + 8 + b.length, 8);
  const ch = (len, type) => { const h = Buffer.alloc(8); h.writeUInt32LE(len, 0); h.writeUInt32LE(type, 4); return h; };
  return Buffer.concat([head, ch(j.length, JSON_CHUNK), j, ch(b.length, BIN_CHUNK), b]);
}

const modelDir = path.join(app, 'assets/models');
fs.rmSync(modelDir, { recursive: true, force: true });
fs.mkdirSync(modelDir, { recursive: true });
const manifest = [];
for (const file of fs.readdirSync(path.join(web, 'models')).filter((f) => f.endsWith('.glb')).sort()) {
  const name = file.replace('.glb', '');
  const { json, bin } = readGlb(fs.readFileSync(path.join(web, 'models', file)));

  // images out to their own files
  const imageFiles = (json.images || []).map((img, i) => {
    const view = json.bufferViews[img.bufferView];
    const ext = img.mimeType === 'image/png' ? 'png' : 'jpg';
    const out = `${name}-${i}.${ext}`;
    fs.writeFileSync(path.join(modelDir, out), bin.subarray(view.byteOffset || 0, (view.byteOffset || 0) + view.byteLength));
    return out;
  });
  // each material remembers which image fills which slot; GLTFLoader keeps extras as userData
  for (const m of json.materials || []) {
    const tex = {};
    const take = (slot, ref) => { if (ref) tex[SLOTS[slot]] = imageFiles[json.textures[ref.index].source]; };
    take('baseColorTexture', m.pbrMetallicRoughness?.baseColorTexture);
    if (m.pbrMetallicRoughness) delete m.pbrMetallicRoughness.baseColorTexture;
    for (const slot of ['normalTexture', 'emissiveTexture']) { take(slot, m[slot]); delete m[slot]; }
    m.extras = { ...(m.extras || {}), textures: tex };
  }
  const imageViews = new Set((json.images || []).map((img) => img.bufferView));
  delete json.images; delete json.textures; delete json.samplers;

  // repack the binary without the image bytes
  const remap = new Map(), parts = [];
  let size = 0;
  json.bufferViews = json.bufferViews.filter((v, i) => {
    if (imageViews.has(i)) return false;
    const bytes = bin.subarray(v.byteOffset || 0, (v.byteOffset || 0) + v.byteLength);
    const gap = (4 - (size % 4)) % 4;
    if (gap) { parts.push(Buffer.alloc(gap)); size += gap; }
    v.byteOffset = size;
    parts.push(bytes); size += bytes.length;
    remap.set(i, remap.size);
    return true;
  });
  for (const a of json.accessors) if (a.bufferView !== undefined) a.bufferView = remap.get(a.bufferView);
  const packed = Buffer.concat(parts);
  json.buffers = [{ byteLength: packed.length }];
  fs.writeFileSync(path.join(modelDir, file), writeGlb(json, packed));
  manifest.push({ name, file, textures: imageFiles });
}

// metro needs every asset as a static require()
const lines = manifest.map(({ name, file, textures }) =>
  `  ${name}: { model: require('../../assets/models/${file}'), textures: { ${textures.map((t) => `'${t}': require('../../assets/models/${t}')`).join(', ')} } },`);
fs.writeFileSync(path.join(out, 'models.ts'), banner + '/* eslint-disable */\nexport const MODELS: Record<string, { model: number; textures: Record<string, number> }> = {\n' + lines.join('\n') + '\n};\n');
const total = fs.readdirSync(modelDir).reduce((s, f) => s + fs.statSync(path.join(modelDir, f)).size, 0);
console.log(`models: ${manifest.length} fighters, ${(total / 1e6).toFixed(1)} MB -> assets/models/`);
